//! `eel-completeness report`, combines scan + trace into docs/audit/completeness-report.md

use crate::allowlist::Allowlist;
use anyhow::{Context, Result};
use std::path::Path;

pub fn run(root: &Path, allowlist: &Allowlist) -> Result<()> {
    let findings = crate::scan::run(root, allowlist)?;
    let coverage = crate::trace::run(
        root,
        Path::new("docs/plans/TRACEABILITY.yaml"),
        false, // report mode: don't fail on gap; just emit
    )?;
    let _ = coverage; // exit code ignored in report mode

    let report_dir = root.join("docs").join("audit");
    std::fs::create_dir_all(&report_dir)
        .with_context(|| format!("creating {}", report_dir.display()))?;

    let out = report_dir.join("completeness-report.md");

    let mut md = String::from("# Completeness Report\n\n");
    md.push_str(&format!(
        "Generated by `eel-completeness report` on `{}`.\n\n",
        chrono::Local::now().format("%Y-%m-%d %H:%M:%S %Z")
    ));

    // Summary table
    let errors = findings
        .iter()
        .filter(|f| matches!(f.severity, crate::finding::Severity::Error) && !f.allowlisted)
        .count();
    let warnings = findings
        .iter()
        .filter(|f| matches!(f.severity, crate::finding::Severity::Warning) && !f.allowlisted)
        .count();
    let infos = findings
        .iter()
        .filter(|f| matches!(f.severity, crate::finding::Severity::Info) && !f.allowlisted)
        .count();
    let suppressed = findings.iter().filter(|f| f.allowlisted).count();

    md.push_str("## Summary\n\n");
    md.push_str("| Category | Count |\n|---|---|\n");
    md.push_str(&format!("| Errors (actionable) | {errors} |\n"));
    md.push_str(&format!("| Warnings | {warnings} |\n"));
    md.push_str(&format!("| Info | {infos} |\n"));
    md.push_str(&format!("| Allowlisted (suppressed) | {suppressed} |\n"));
    md.push_str("\n## Findings\n\n");

    if findings.is_empty() {
        md.push_str("No findings.\n");
    } else {
        md.push_str("| File | Line | Kind | Severity | Message | Allowlisted |\n");
        md.push_str("|---|---|---|---|---|---|\n");
        for f in &findings {
            let al = if f.allowlisted {
                f.adr.as_deref().unwrap_or("yes")
            } else {
                "no"
            };
            md.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} |\n",
                f.file, f.line, f.kind, f.severity, f.message, al
            ));
        }
    }

    md.push_str("\n*See `docs/audit/traceability-report.md` for test coverage details.*\n");

    std::fs::write(&out, &md).with_context(|| format!("writing {}", out.display()))?;
    eprintln!("completeness report: {}", out.display());
    Ok(())
}
