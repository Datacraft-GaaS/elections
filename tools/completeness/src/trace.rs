//! `eel-completeness trace` — reads test trace annotations and builds a
//! coverage map against TRACEABILITY.yaml.
//!
//! Annotation syntax (per docs/plans/00-principles.md §2):
//!   Rust:    #[trace("EC-DAT-01","FR-M02-007","AC-M02-03")]
//!   Python:  @pytest.mark.trace("EC-DAT-01", ...)
//!   Elixir:  @tag trace: ["EC-DAT-01", ...]
//!   Flutter: testWidgets('desc [EC-MOB-01]', ...)
//!   Playwright/Vitest: test('desc @EC-SCL-01', ...)

use anyhow::{Context, Result};
use regex::Regex;
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};
use std::path::Path;
use walkdir::WalkDir;

#[derive(Debug, Serialize, Deserialize)]
pub struct TraceabilityRow {
    pub id: String,
    #[serde(default)]
    pub description: Option<String>,
    #[serde(default)]
    pub requirement: Option<String>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct TraceabilityFile {
    pub entries: Vec<TraceabilityRow>,
}

/// Map from EC-ID -> list of (file, line) test locations found
pub type CoverageMap = HashMap<String, Vec<(String, usize)>>;

const SKIP_DIRS: &[&str] = &[
    ".git",
    "target",
    "node_modules",
    ".cache",
    "_build",
    ".elixir_ls",
    "deps",
    ".dart_tool",
];

pub fn run(root: &Path, traceability_path: &Path, fail_on_gap: bool) -> Result<i32> {
    let traceability = load_traceability(root, traceability_path)?;
    let coverage = collect_coverage(root)?;

    // Build traceability report
    let report_dir = root.join("docs").join("audit");
    std::fs::create_dir_all(&report_dir)
        .with_context(|| format!("creating {}", report_dir.display()))?;

    let report_path = report_dir.join("traceability-report.md");
    let junit_path = report_dir.join("traceability-junit.xml");

    let mut gaps: Vec<String> = Vec::new();
    let mut md = String::from("# Traceability Report\n\n");
    md.push_str("| EC-ID | Description | Tests Found | Status |\n");
    md.push_str("|---|---|---|---|\n");

    for row in &traceability.entries {
        let tests = coverage.get(&row.id).cloned().unwrap_or_default();
        let status = if tests.is_empty() {
            gaps.push(row.id.clone());
            "GAP"
        } else {
            "OK"
        };
        let desc = row.description.as_deref().unwrap_or("");
        let tests_str = tests
            .iter()
            .map(|(f, l)| format!("{f}:{l}"))
            .collect::<Vec<_>>()
            .join(", ");
        md.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            row.id, desc, tests_str, status
        ));
    }

    // EC-IDs in coverage but not in traceability file (orphaned annotations)
    let known: HashSet<&str> = traceability.entries.iter().map(|r| r.id.as_str()).collect();
    let orphaned: Vec<&str> = coverage
        .keys()
        .map(|s| s.as_str())
        .filter(|id| !known.contains(id))
        .collect();

    if !orphaned.is_empty() {
        md.push_str("\n## Orphaned annotations (not in TRACEABILITY.yaml)\n\n");
        for id in &orphaned {
            md.push_str(&format!("- {id}\n"));
        }
    }

    md.push_str(&format!(
        "\n*Generated by eel-completeness trace — {} entries, {} gaps, {} orphaned.*\n",
        traceability.entries.len(),
        gaps.len(),
        orphaned.len()
    ));

    std::fs::write(&report_path, &md)
        .with_context(|| format!("writing {}", report_path.display()))?;
    eprintln!("traceability report: {}", report_path.display());

    // JUnit output
    emit_junit_trace(&traceability, &coverage, &junit_path)?;
    eprintln!("traceability JUnit: {}", junit_path.display());

    if !gaps.is_empty() {
        eprintln!("GAPS (zero passing tests): {}", gaps.join(", "));
        if fail_on_gap {
            return Ok(1);
        }
    }
    Ok(0)
}

fn load_traceability(root: &Path, rel: &Path) -> Result<TraceabilityFile> {
    let path = if rel.is_absolute() {
        rel.to_path_buf()
    } else {
        root.join(rel)
    };
    if !path.exists() {
        eprintln!(
            "TRACEABILITY.yaml not found at {} — returning empty",
            path.display()
        );
        return Ok(TraceabilityFile::default());
    }
    let content =
        std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let tf: TraceabilityFile =
        serde_yaml::from_str(&content).with_context(|| format!("parsing {}", path.display()))?;
    Ok(tf)
}

fn collect_coverage(root: &Path) -> Result<CoverageMap> {
    let mut map: CoverageMap = HashMap::new();

    // Rust: #[trace("EC-XXX-01", ...)]
    let rust_re = Regex::new(r#"#\[trace\s*\(([^)]+)\)\]"#).unwrap();
    // Python: @pytest.mark.trace("EC-XXX-01", ...)
    let py_re = Regex::new(r#"@pytest\.mark\.trace\s*\(([^)]+)\)"#).unwrap();
    // Elixir: @tag trace: ["EC-XXX-01", ...]
    let ex_re = Regex::new(r#"@tag\s+trace:\s*\[([^\]]+)\]"#).unwrap();
    // Flutter: testWidgets('... [EC-MOB-01]')
    let flutter_re = Regex::new(r#"\[([A-Z]{2}-[A-Z]{2,6}-\d{2,4})\]"#).unwrap();
    // Playwright/Vitest: test('... @EC-SCL-01')
    let js_re = Regex::new(r#"@([A-Z]{2}-[A-Z]{2,6}-\d{2,4})"#).unwrap();
    // EC-ID bare string extractor
    let id_re = Regex::new(r#"["\']([A-Z]{2}-[A-Z]{2,6}-\d{2,4})["\']"#).unwrap();

    let walker = WalkDir::new(root)
        .follow_links(false)
        .into_iter()
        .filter_entry(|e| {
            if e.file_type().is_dir() {
                let n = e.file_name().to_string_lossy();
                return !SKIP_DIRS.contains(&n.as_ref());
            }
            true
        });

    for entry in walker.filter_map(|e| e.ok()) {
        if !entry.file_type().is_file() {
            continue;
        }
        let path = entry.path();
        let ext = path.extension().and_then(|e| e.to_str()).unwrap_or("");
        let rel = path
            .strip_prefix(root)
            .unwrap_or(path)
            .to_string_lossy()
            .into_owned();

        let (primary_re, id_extractor): (&Regex, &Regex) = match ext {
            "rs" => (&rust_re, &id_re),
            "py" => (&py_re, &id_re),
            "ex" | "exs" => (&ex_re, &id_re),
            "dart" => (&flutter_re, &flutter_re),
            "ts" | "tsx" | "js" | "jsx" | "mts" | "cts" => (&js_re, &js_re),
            _ => continue,
        };

        let content = match std::fs::read_to_string(path) {
            Ok(c) => c,
            Err(_) => continue,
        };

        for (lineno, line) in content.lines().enumerate() {
            let lineno = lineno + 1;
            if primary_re.is_match(line) {
                // Extract all EC-IDs from the annotation
                for cap in id_extractor.captures_iter(line) {
                    let id = cap.get(1).unwrap().as_str().to_owned();
                    map.entry(id).or_default().push((rel.clone(), lineno));
                }
            }
        }
    }

    Ok(map)
}

fn emit_junit_trace(
    traceability: &TraceabilityFile,
    coverage: &CoverageMap,
    out: &Path,
) -> Result<()> {
    use quick_junit::{NonSuccessKind, Report, TestCase, TestCaseStatus, TestSuite};

    let mut suite = TestSuite::new("eel-traceability");
    for row in &traceability.entries {
        let tests = coverage.get(&row.id).cloned().unwrap_or_default();
        let status = if tests.is_empty() {
            let mut s = TestCaseStatus::non_success(NonSuccessKind::Failure);
            s.set_message(format!("{}: no tests found", row.id));
            s
        } else {
            TestCaseStatus::success()
        };
        let tc = TestCase::new(row.id.clone(), status);
        suite.add_test_case(tc);
    }
    let mut report = Report::new("eel-traceability");
    report.add_test_suite(suite);
    let xml = report.to_string()?;
    std::fs::write(out, xml).with_context(|| format!("writing {}", out.display()))?;
    Ok(())
}
