#!/usr/bin/env python3
"""Seed docs/plans/TRACEABILITY.yaml from module pages and the edge-case matrix.

Rows: one per FR-/AC- ID found in docs/plans/modules/*.md and one per EC-ID in
docs/plans/08-edge-case-matrix.md. Each row starts with an empty test list;
work packages append test IDs as they land. Re-running preserves existing
test lists (merge by row id) so the file can be regenerated safely.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLANS = ROOT / "docs" / "plans"
OUT = PLANS / "TRACEABILITY.yaml"

FR_RE = re.compile(r"\b(FR-M\d{2}-\d{3})\b")
AC_RE = re.compile(r"\b(AC-M\d{2}-\d{2})\b")
EC_RE = re.compile(r"^\|\s*(EC-[A-Z]{3}-\d{2})\s*\|", re.M)
MOD_RE = re.compile(r"^# (M\d{2}) ([a-z0-9-]+)", re.M)
WP_RE = re.compile(r"\|\s*Owning work package\s*\|\s*(WP-\d\.\d+[a-z]?)")


def existing_tests(path: Path) -> dict[str, list[str]]:
    """Very small YAML reader for the shape this script writes."""
    if not path.exists():
        return {}
    tests: dict[str, list[str]] = {}
    cur: str | None = None
    for line in path.read_text().splitlines():
        m = re.match(r"^  (\S+):\s*$", line)
        if m:
            cur = m.group(1)
            tests[cur] = []
            continue
        m = re.match(r"^      - (\S+)", line)
        if m and cur:
            tests[cur].append(m.group(1))
    return tests


def main() -> int:
    keep = existing_tests(OUT)
    lines: list[str] = [
        "# Traceability matrix seed. Generated by tools/completeness/seed_traceability.py.",
        "# Each row maps a requirement (FR), acceptance criterion (AC), or edge case (EC)",
        "# to the test IDs that prove it. Empty lists fail the Wave 6 completeness audit.",
        "rows:",
    ]
    count = 0
    for page in sorted((PLANS / "modules").glob("*.md")):
        text = page.read_text()
        mod = MOD_RE.search(text)
        if not mod:
            print(f"skip {page.name}: no H1", file=sys.stderr)
            continue
        mnum, slug = mod.groups()
        wp = WP_RE.search(text)
        wp_id = wp.group(1) if wp else "WP-unassigned"
        ids = sorted(set(FR_RE.findall(text)) | set(AC_RE.findall(text)))
        for rid in ids:
            lines.append(f"  {rid}:")
            lines.append(f"    module: {slug}")
            lines.append(f"    wp: {wp_id}")
            lines.append("    tests:")
            for t in keep.get(rid, []):
                lines.append(f"      - {t}")
            count += 1
    matrix = (PLANS / "08-edge-case-matrix.md").read_text()
    for ec in sorted(set(EC_RE.findall(matrix))):
        lines.append(f"  {ec}:")
        lines.append("    module: cross-cutting")
        lines.append("    wp: all-applicable")
        lines.append("    tests:")
        for t in keep.get(ec, []):
            lines.append(f"      - {t}")
        count += 1
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} with {count} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
