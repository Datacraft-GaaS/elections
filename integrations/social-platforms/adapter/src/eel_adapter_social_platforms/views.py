"""Request/response models for the social-platforms adapter."""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field


class Request(BaseModel):
	model_config = ConfigDict(
		extra="forbid", validate_by_name=True, validate_by_alias=True
	)

	contentUrl: str = Field(..., description="contentUrl (PII B (Internal))")
	platformUserId: str = Field(..., description="platformUserId (PII A (Restricted))")
	request_id: str = Field(..., description="UUIDv7 idempotency key")


class Response(BaseModel):
	model_config = ConfigDict(
		extra="forbid", validate_by_name=True, validate_by_alias=True
	)

	request_id: str
	ok: bool = True
	message: str = "ok"
	contentUrl: str | None = None
	platformUserId: str | None = None
