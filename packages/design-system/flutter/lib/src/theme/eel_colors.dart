// Hand-maintained. The token *maps* in tokens.dart are generated by
// `dart run tool/codegen_tokens.dart`; this file holds the typed classes and is
// edited by hand. test/token_parity_test.dart enforces that the maps and these
// classes agree, so a token change that is not reflected here fails the suite.
// (This header previously claimed the file was generated, which was not true
// and discouraged exactly the edits it needed.)

