  factory EelColors.dark() => const EelColors(
        brightness: Brightness.dark,
        brandPrimary: Color(0xFF4F83F1),
        brandPrimaryHover: Color(0xFF6B9EFF),
        brandSecondary: Color(0xFF31C48D),
