  /// The resolved palette for [context]'s brightness.
  ///
  /// The conventional Flutter accessor for a [ThemeExtension]. Apps that need
  /// a context-sensitive colour read it this way rather than through a static,
  /// so light and dark both resolve correctly.
  static EelColors of(BuildContext context) {
    return Theme.of(context).extension<EelColors>() ??
        (Theme.of(context).brightness == Brightness.dark
            ? EelColors.dark()
            : EelColors.light());
  }

  // ---------------------------------------------------------------------
  // Static aliases for the app tier.
  //
  // The app tier reads palette entries as statics, which keeps a screen
  // readable without threading a BuildContext through a colour. These map onto
  // the token names in tokens.json rather than inventing a second palette, so
  // there is one source of truth for each value.
  // ---------------------------------------------------------------------

  /// Page background, the paper a screen is printed on.
  // ---------------------------------------------------------------------
  // Aliases for the app tier's vocabulary.
  //
  // The app tier reaches for these Material-familiar names; the token set
  // names the same values brandPrimary/surface/textPrimary. These forward
  // rather than duplicate, so a token change is still made in one place.
  // ---------------------------------------------------------------------

  /// The primary action colour.
  Color get primary => brandPrimary;

  /// [primary] de-emphasised, for an inactive control or a quiet accent.
  Color get primaryMuted => brandPrimary.withValues(alpha: 0.62);

  /// [primary] as a background to sit behind text of [onSurface].
  Color get primarySurface => brandPrimary.withValues(alpha: 0.12);

  /// Text or icons drawn on top of [surface].
  Color get onSurface => textPrimary;

  /// Secondary text or icons drawn on top of [surface].
  Color get onSurfaceMuted => textSecondary;

  static final EelColors _light = EelColors.light();

  /// Page background, the paper a screen is printed on.
  static Color get paper => _light.background;

  /// Default body text.
  static Color get ink => _light.textPrimary;

  /// Secondary text: help text and metadata.
  static Color get inkSoft => _light.textSecondary;

  /// Disabled text.
  static Color get inkFaint => _light.textDisabled;

  /// Hairline rules and dividers.
  static Color get line => _light.border;

  /// Stronger divider, where a hairline is too faint to see in daylight.
  static Color get lineStrong => _light.textSecondary;

  /// Raised surface, such as a card sitting above the page.
  static Color get raised => _light.surface;

  /// Primary action colour.
  static Color get green => _light.brandSecondary;

  /// Primary action colour, pressed.
  static Color get greenDeep => _light.success;

  /// Tinted green background, for a success banner.
  static Color get greenTint => _light.success.withValues(alpha: 0.12);

  /// Green rule, for a success banner's leading edge.
  static Color get greenLine => _light.success;

  /// Award or accreditation colour.
  static Color get gold => _light.warning;

  /// Tinted gold background.
  static Color get goldTint => _light.warning.withValues(alpha: 0.12);

  /// Seal colour: the official-stamp accent.
  static Color get seal => _light.info;

  /// Seal colour, pressed or emphasised.
  static Color get sealDeep => _light.info;

  /// Tinted seal background.
  static Color get sealTint => _light.info.withValues(alpha: 0.12);

  @override
  EelColors copyWith({
    Brightness? brightness,
    Color? brandPrimary,
    Color? brandPrimaryHover,
    Color? brandSecondary,
    Color? success,
    Color? warning,
    Color? danger,
    Color? info,
    Color? background,
    Color? surface,
    Color? border,
    Color? textPrimary,
    Color? textSecondary,
    Color? textDisabled,
    Color? textInverse,
    Color? textLink,
  }) {
    return EelColors(
      brightness: brightness ?? this.brightness,
      brandPrimary: brandPrimary ?? this.brandPrimary,
      brandPrimaryHover: brandPrimaryHover ?? this.brandPrimaryHover,
      brandSecondary: brandSecondary ?? this.brandSecondary,
      success: success ?? this.success,
      warning: warning ?? this.warning,
      danger: danger ?? this.danger,
      info: info ?? this.info,
      background: background ?? this.background,
      surface: surface ?? this.surface,
      border: border ?? this.border,
      textPrimary: textPrimary ?? this.textPrimary,
      textSecondary: textSecondary ?? this.textSecondary,
      textDisabled: textDisabled ?? this.textDisabled,
      textInverse: textInverse ?? this.textInverse,
      textLink: textLink ?? this.textLink,
    );
  }

  @override
  EelColors lerp(ThemeExtension<EelColors>? other, double t) {
    if (other is! EelColors) return this;
    return EelColors(
      brightness: t < 0.5 ? brightness : other.brightness,
      brandPrimary: Color.lerp(brandPrimary, other.brandPrimary, t)!,
      brandPrimaryHover:
          Color.lerp(brandPrimaryHover, other.brandPrimaryHover, t)!,
      brandSecondary: Color.lerp(brandSecondary, other.brandSecondary, t)!,
      success: Color.lerp(success, other.success, t)!,
      warning: Color.lerp(warning, other.warning, t)!,
      danger: Color.lerp(danger, other.danger, t)!,
      info: Color.lerp(info, other.info, t)!,
      background: Color.lerp(background, other.background, t)!,
      surface: Color.lerp(surface, other.surface, t)!,
      border: Color.lerp(border, other.border, t)!,
      textPrimary: Color.lerp(textPrimary, other.textPrimary, t)!,
      textSecondary: Color.lerp(textSecondary, other.textSecondary, t)!,
      textDisabled: Color.lerp(textDisabled, other.textDisabled, t)!,
      textInverse: Color.lerp(textInverse, other.textInverse, t)!,
      textLink: Color.lerp(textLink, other.textLink, t)!,
    );
  }
}

