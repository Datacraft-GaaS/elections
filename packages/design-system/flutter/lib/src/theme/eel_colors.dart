  /// Colour-blind safe categorical palette (fixed across brightness).
  static const colorblindSafe = <String, Color>{
    'blue': Color(0xFF0072B2),
    'orange': Color(0xFFE69F00),
    'sky': Color(0xFF56B4E9),
