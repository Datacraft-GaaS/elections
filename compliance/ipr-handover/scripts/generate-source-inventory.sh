#!/usr/bin/env bash
# generate-source-inventory.sh
# Regenerates compliance/ipr-handover/source-inventory-full.yaml
# Usage: bash compliance/ipr-handover/scripts/generate-source-inventory.sh [REPO_ROOT]
#
# Requires: find, sha256sum (GNU coreutils), yq v4
# Excludes build artefacts: target/, .venv/, node_modules/, _build/, deps/,
#   .dart_tool/, dist/, dist-*/,  build/
#
# Output: compliance/ipr-handover/source-inventory-full.yaml

set -euo pipefail

REPO_ROOT="${1:-$(git rev-parse --show-toplevel)}"
OUTPUT="${REPO_ROOT}/compliance/ipr-handover/source-inventory-full.yaml"
DATE=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
GIT_HASH=$(git -C "${REPO_ROOT}" rev-parse HEAD 2>/dev/null || echo "unknown")

SCAN_DIRS=(
  services
  packages
  platform
  edge
  integrations
  tools
  docs
  compliance
  environments
  chaos
  loadtest
  reproducibility
  air-gapped-build
  operations
)

EXCLUDE_DIRS=(
  target
  .venv
  node_modules
  _build
  deps
  .dart_tool
  dist
  build
)

# Build the -prune expression for excluded directories
PRUNE_EXPR=()
for dir in "${EXCLUDE_DIRS[@]}"; do
  PRUNE_EXPR+=(-name "${dir}" -prune -o)
done

echo "Scanning ${REPO_ROOT} ..."
echo "Output: ${OUTPUT}"

{
  echo "# Source inventory: all eel custom software components"
  echo "# Auto-generated by compliance/ipr-handover/scripts/generate-source-inventory.sh"
  echo "# Do not edit manually."
  echo ""
  echo "inventory_version: \"1.0\""
  echo "date: \"${DATE}\""
  echo "git_hash: \"${GIT_HASH}\""
  echo "licence_default: Apache-2.0"
  echo ""
  echo "files:"
} > "${OUTPUT}"

for scan_dir in "${SCAN_DIRS[@]}"; do
  full_path="${REPO_ROOT}/${scan_dir}"
  if [ ! -d "${full_path}" ]; then
    continue
  fi

  # Use find with pruning
  find "${full_path}" \
    "${PRUNE_EXPR[@]}" \
    -type f -print | sort | while read -r file; do
      rel="${file#${REPO_ROOT}/}"
      hash=$(sha256sum "${file}" | awk '{print $1}')

      # Infer owner-service from path prefix
      owner="eel"
      case "${rel}" in
        services/transparency-svc/*) owner="transparency-svc" ;;
        services/boundary-svc/*)     owner="boundary-svc" ;;
        services/rts-svc/*)          owner="rts-svc" ;;
        services/bvr-svc/*)          owner="bvr-svc" ;;
        services/abis-svc/*)         owner="abis-svc" ;;
        services/bvi-svc/*)          owner="bvi-svc" ;;
        services/biometric-edge-svc/*) owner="biometric-edge-svc" ;;
        services/portal-svc/*)       owner="portal-svc" ;;
        services/ecc-svc/*)          owner="ecc-svc" ;;
        services/queue-svc/*)        owner="queue-svc" ;;
        services/inventory-svc/*)    owner="inventory-svc" ;;
        services/ai-platform-svc/*)  owner="ai-platform-svc" ;;
        services/field-mobile-svc/*) owner="field-mobile-svc" ;;
        services/vprs-svc/*)         owner="vprs-svc" ;;
        services/crms-svc/*)         owner="crms-svc" ;;
        services/governance-svc/*)   owner="governance-svc" ;;
        services/training-svc/*)     owner="training-svc" ;;
        services/support-admin-svc/*) owner="support-admin-svc" ;;
        services/*)                  owner="services-shared" ;;
        packages/openapi-contracts/*) owner="openapi-contracts" ;;
        packages/event-schemas/*)    owner="event-schemas" ;;
        packages/*)                  owner="packages-shared" ;;
        platform/*)                  owner="platform" ;;
        edge/*)                      owner="edge" ;;
        integrations/*)              owner="integrations" ;;
        tools/*)                     owner="tools" ;;
        docs/*)                      owner="docs" ;;
        compliance/*)                owner="compliance" ;;
        environments/*)              owner="environments" ;;
        chaos/*)                     owner="chaos" ;;
        loadtest/*)                  owner="loadtest" ;;
        reproducibility/*)           owner="reproducibility" ;;
        air-gapped-build/*)          owner="air-gapped-build" ;;
        operations/*)                owner="operations" ;;
      esac

      printf '  - path: "%s"\n    sha256: "%s"\n    licence: Apache-2.0\n    owner: "%s"\n' \
        "${rel}" "${hash}" "${owner}"
    done >> "${OUTPUT}"
done

echo "Done. Inventory written to ${OUTPUT}"
wc -l "${OUTPUT}"
